import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { collectCompositeScoreReport } from "./composite-report.js";
import { collectRepositoryInventory, SOURCE_ROLE_VERSION } from "./inventory.js";
import { collectStaticMeasurements } from "./static-measurements.js";

const roots: string[] = [];
function fixture(files: Record<string, string>): string {
	const root = mkdtempSync(join(tmpdir(), "metrics-provenance-"));
	roots.push(root);
	for (const [path, content] of Object.entries(files)) {
		mkdirSync(dirname(join(root, path)), { recursive: true });
		writeFileSync(join(root, path), content);
	}
	return root;
}
afterEach(() => { for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true }); });

const branchy = (name: string, branches: number): string =>
	`export function ${name}(n: number) {\n${Array.from({ length: branches }, (_, i) => `\tif (n === ${i}) return ${i};`).join("\n")}\n\treturn -1;\n}\n`;

describe("the shared census keeps path-only roles; only the score report applies evidence", () => {
	const files = { "src/authored.ts": branchy("authored", 3), "src/self-declared.ts": `export const first = 1;\n// AUTO-GENERATED by scripts/gen.py\n${branchy("declared", 40)}`,
		".yarn/releases/yarn.cjs": branchy("yarn", 200) };
	it("leaves every one of these files a product input in the census that the gates and the coverage index read", () => {
		const census = collectRepositoryInventory(fixture(files));
		expect(census.version).toBe(SOURCE_ROLE_VERSION);
		expect(census.files.map(file => [file.path, file.role])).toEqual([[".yarn/releases/yarn.cjs", "product"], ["src/authored.ts", "product"], ["src/self-declared.ts", "product"]]);
	});
	it("measures the self-declared file but not the vendored one in the score pipeline, over the same census", () => {
		const measured = collectStaticMeasurements(fixture(files));
		expect(measured.census.files).toHaveLength(3);
		expect(measured.analysis.inventory.version).toBe("interlinked-source-roles-v5");
		expect(measured.analysis.files.map(file => file.input.path)).toEqual(["src/authored.ts", "src/self-declared.ts"]);
	});
});

describe("a header cannot change a measured burden", () => {
	const body = branchy("big", 60), hand = branchy("small", 3);
	// A banner OUTSIDE the leading comment block only labels the file (a banner in the header sets it aside: see role-header-banner.test.ts).
	const withHeader = collectCompositeScoreReport(fixture({ "src/a.ts": `export const first = 1;\n// @generated\n${body}`, "src/b.ts": hand }));
	const without = collectCompositeScoreReport(fixture({ "src/a.ts": `export const first = 1;\n// note\n${body}`, "src/b.ts": hand }));
	it("gives the same observed score and the same value for every metric", () => {
		expect(withHeader.observedScore).toBe(without.observedScore);
		expect(withHeader.metrics.map(metric => [metric.id, metric.value, metric.score])).toEqual(without.metrics.map(metric => [metric.id, metric.value, metric.score]));
		expect(withHeader.scope.measuredFiles).toBe(without.scope.measuredFiles);
	});
	it("still labels the file, and marks a maximum that sits in it", () => {
		expect(withHeader.provenance.declared.files).toEqual([expect.objectContaining({ path: "src/a.ts", detail: "line 2: @generated" })]);
		expect(without.provenance.declared.total).toBe(0);
		expect(withHeader.metrics.find(metric => metric.id === "cyclomatic")?.top).toMatchObject({ file: "src/a.ts", declaredGenerated: true });
		expect(without.metrics.find(metric => metric.id === "cyclomatic")?.top?.declaredGenerated).toBeUndefined();
	});
});

describe("the composite score report shows the split and keeps naming the file behind each maximum", () => {
	const files = { "src/authored.ts": branchy("authored", 4), ".yarn/releases/yarn.cjs": branchy("yarn", 300),
		"src/gen.ts": `export const first = 1;\n// @generated\n${branchy("big", 90)}`, "src/hand.ts": `// Generated IDs are stable.\n${branchy("table", 6)}`,
		"mocks/orders.ts": "export const orders = [1, 2, 3];\n" };
	const report = collectCompositeScoreReport(fixture(files));
	it("excludes vendored code from every maximum but keeps the header-only file, marked", () => {
		const cyclomatic = report.metrics.find(metric => metric.id === "cyclomatic");
		expect(cyclomatic?.value).toBe(91);
		expect(cyclomatic?.top).toMatchObject({ file: "src/gen.ts", name: "big", value: 91, declaredGenerated: true });
	});
	it("reports the split with evidence kinds and lists the declared file apart", () => {
		expect(report.rolesVersion).toBe("interlinked-source-roles-v5");
		expect(report.provenance.authored.files).toBe(3);
		expect(report.provenance.setAside.vendor).toMatchObject({ files: 1, byKind: { "tool-path": 1 } });
		expect(report.provenance.setAside.generated.files).toBe(0);
		expect(report.provenance.moved).toMatchObject({ total: 2, toRole: { vendor: 1, test: 1 } });
		expect(report.provenance.declared.files).toEqual([expect.objectContaining({ path: "src/gen.ts", detail: "line 2: @generated" })]);
		expect(report.provenance.line).toBe("authored 3 files (1 declare generated, still measured) · generated 0 · vendored 1 · unlinted 0 · moved to test by path 1");
		expect(report.scope.exclusions.map(file => file.path)).toContain(".yarn/releases/yarn.cjs");
		expect(report.scope.exclusions.map(file => file.path)).not.toContain("src/gen.ts");
	});
	it("keeps the census hashes, so saved evidence still matches the same files", () => {
		const census = collectRepositoryInventory(fixture(files));
		expect([report.inputHash, report.sourceHash]).toEqual([census.inputHash, census.sourceHash]);
	});
});
