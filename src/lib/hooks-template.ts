/** Auto-heal after a failed daemon round-trip. A module-global cooldown cannot
 * coordinate hooks because every invocation is a new Node process; the shared
 * O_EXCL lease below is the cross-process single-flight. */
const HARNESS_START_LOCK_PATH = join(CONFIG_DIR, ".harness-start.lock");
// Canonical startup permits a 60s cold-boot window. This standalone hook exits
// after transferring the lease and therefore cannot heartbeat it; keep the
// same 75s jitter margin as startup-lock.ts so a slow live child is not
// duplicated by the next agent hook under memory pressure.
const HARNESS_START_LOCK_TTL_MS = 75000;
const HARNESS_START_LOCK_INITIALIZATION_GRACE_MS = 2000;

function processIsAlive(pid) {
    try { process.kill(pid, 0); return true; }
    catch (err) { return Boolean(err && err.code === "EPERM"); }
}

function readHarnessStartHolder() {
    try {
        const raw = JSON.parse(readFileSync(HARNESS_START_LOCK_PATH, "utf-8"));
        if (!raw || typeof raw.pid !== "number" || typeof raw.at !== "number") return null;
        return raw;
    } catch (_err) { void 0; return null; }
}

function writeHarnessStartLock(now) {
    let fd = null;
    try {
        fd = openSync(HARNESS_START_LOCK_PATH, "wx");
        writeFileSync(fd, JSON.stringify({ pid: process.pid, at: now }));
        return true;
    } catch (_err) {
        return false;
    } finally {
        if (fd !== null) try { closeSync(fd); } catch (_err) { void 0; }
    }
}

function harnessStartLockIsInitializing(now) {
    try {
        return now - statSync(HARNESS_START_LOCK_PATH).mtimeMs <= HARNESS_START_LOCK_INITIALIZATION_GRACE_MS;
    } catch (_err) { void 0; return false; }
}

let harnessStartLockTempSequence = 0;
function replaceHarnessStartHolder(expected, next) {
    const tempPath = HARNESS_START_LOCK_PATH + "." + process.pid + "." + (++harnessStartLockTempSequence) + ".tmp";
    try {
        writeFileSync(tempPath, JSON.stringify(next), { flag: "wx" });
        const current = readHarnessStartHolder();
        if (!current || current.pid !== expected.pid || current.at !== expected.at) return false;
        renameSync(tempPath, HARNESS_START_LOCK_PATH);
        return true;
    } catch (_err) {
        void 0;
        return false;
    } finally {
        try { unlinkSync(tempPath); } catch (_err) { void 0; }
    }
}

function releaseHarnessStartLock(expectedPid) {
    const holder = readHarnessStartHolder();
    if (!holder || holder.pid !== expectedPid) return;
    try { unlinkSync(HARNESS_START_LOCK_PATH); } catch (_err) { void 0; }
}

function acquireHarnessStartLock(now = Date.now()) {
    try { mkdirSync(CONFIG_DIR, { recursive: true }); } catch (_err) { void 0; }
    if (writeHarnessStartLock(now)) return true;
    const holder = readHarnessStartHolder();
    if (!holder && harnessStartLockIsInitializing(now)) return false;
    const fresh = holder && now - holder.at <= HARNESS_START_LOCK_TTL_MS && processIsAlive(holder.pid);
    if (fresh) return false;
    try { unlinkSync(HARNESS_START_LOCK_PATH); } catch (_err) { void 0; }
    return writeHarnessStartLock(now);
}

function exactDaemonCommand(harnessEvent) {
    if (harnessEvent.tool_name !== "Bash") return false;
    const command = harnessEvent.tool_input && harnessEvent.tool_input.command;
    if (typeof command !== "string" || /[;&|><\`$(){}\\n]/.test(command)) return false;
    const trimmed = command.trim();
    const cliPattern = "(?:interlinked|node (?:[A-Za-z0-9_./:-]{1,160}/)?dist/index[.]js)";
    const lifecycle = new RegExp("^" + cliPattern + " (?:harness (?:start|restart|status)(?: --[A-Za-z0-9_-]+){0,8}|doctor(?: --[A-Za-z0-9_-]+){0,8})$");
    const disable = new RegExp("^" + cliPattern + " disable(?: (?:--(?:team|uninstall|keep-config|force)|--(?:reason|until) [A-Za-z0-9_./:@-]{1,80})){0,6}$");
    if (lifecycle.test(trimmed) || disable.test(trimmed)) return true;
    return new RegExp("^" + cliPattern + " install-hooks (?:--refresh --preserve-mode|--preserve-mode --refresh)$").test(trimmed);
}

