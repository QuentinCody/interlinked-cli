function generateMetrics(): string {
	const lines: string[] = [
		"# Quality-Metric Caps",
		"",
		"<!-- Auto-generated by scripts/generate-docs.ts — do not edit manually -->",
		"",
		`The harness enforces ${METRIC_DEFS.length} quality metrics. Every user tunes their own caps in the`,
		"committed `.interlinked/metric-caps.json` (or `interlinked caps set <metric> <value>`);",
		"the values below are the shipped defaults. `interlinked caps` shows the effective cap",
		"per repo, and `interlinked caps explain <metric>` prints these same definitions — so an",
		"agent on any harness-running codebase is never unsure what a metric means.",
		"",
		"| Metric | Config key | Shipped default | Direction |",
		"|--------|-----------|-----------------|-----------|",
	];
	for (const d of METRIC_DEFS) {
		const unit = d.unit ? ` ${d.unit}` : "";
		lines.push(`| \`${d.key}\` | \`${d.configKey}\` | ${d.defaultValue}${unit} | ${d.stricter} is stricter |`);
	}
	lines.push("");
	for (const d of METRIC_DEFS) {
		const unit = d.unit ? ` ${d.unit}` : "";
		lines.push(`## ${d.label} (\`${d.key}\`)`, "");
		lines.push(d.definition, "");
		lines.push(`- **Shipped default:** ${d.defaultValue}${unit} (${d.stricter} is stricter)`);
		lines.push(`- **Configure:** ${d.howToConfigure}`);
		lines.push(`- **Fix when an edit is blocked:** ${d.fixHint}`, "");
	}
	return `${lines.join("\n")}\n`;
}

const files = [
	{ name: "guard-rules.md", generator: generateGuardRules },
	{ name: "quality-checks.md", generator: generateQualityChecks },
	{ name: "structural-checks.md", generator: generateStructuralChecks },
	{ name: "sequence-detectors.md", generator: generateSequenceDetectorsDoc },
	{ name: "configuration.md", generator: generateConfigReference },
	{ name: "cli-reference.md", generator: generateCliReference },
	{ name: "metrics.md", generator: generateMetrics },
];

let generated = 0;
for (const { name, generator } of files) {
	const content = generator();
	const path = join(OUT_DIR, name);
	writeFileSync(path, content);
	console.log(`  Generated: docs/generated/${name}`);
	generated++;
}

console.log(`\n${generated} reference docs generated from code.`);
