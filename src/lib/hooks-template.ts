function acquireQualityWarningDrainLease() {
    try { mkdirSync(QUALITY_WARNING_SPOOL_DIR, { recursive: true }); }
    catch (_err) { void 0; return null; }
    for (let attempt = 0; attempt < 2; attempt++) {
        const ownerToken = process.pid + "-" + randomUUID();
        try {
            writeFileSync(
                QUALITY_WARNING_DRAIN_LOCK_PATH,
                JSON.stringify({ pid: process.pid, at: Date.now(), owner_token: ownerToken }),
                { encoding: "utf-8", flag: "wx", mode: 0o600 },
            );
            return ownerToken;
        } catch (_err) { void 0; }

        let stale = false;
        try {
            const holder = JSON.parse(readFileSync(QUALITY_WARNING_DRAIN_LOCK_PATH, "utf-8"));
            stale = !holder || typeof holder.pid !== "number" || typeof holder.at !== "number"
                ? (Date.now() - statSync(QUALITY_WARNING_DRAIN_LOCK_PATH).mtimeMs) > QUALITY_WARNING_DRAIN_LOCK_TTL_MS
                : !processIsAlive(holder.pid) && (Date.now() - holder.at) > 1000;
        } catch (_err) { void 0; }
        if (!stale) return null;

        // Rename, never unlink by path: only one contender can claim the stale
        // inode, and no contender can delete a replacement live lease.
        const staleClaim = QUALITY_WARNING_DRAIN_LOCK_PATH + ".stale-" + randomUUID();
        try {
            renameSync(QUALITY_WARNING_DRAIN_LOCK_PATH, staleClaim);
            try { unlinkSync(staleClaim); } catch (_err) { void 0; /* best-effort */ }
        } catch (_err) { void 0; return null; }
    }
    return null;
}

function releaseQualityWarningDrainLease(ownerToken) {
    try {
        const holder = JSON.parse(readFileSync(QUALITY_WARNING_DRAIN_LOCK_PATH, "utf-8"));
        if (!holder || holder.owner_token !== ownerToken || holder.pid !== process.pid) return;
        const claimed = QUALITY_WARNING_DRAIN_LOCK_PATH + ".release-" + ownerToken;
        renameSync(QUALITY_WARNING_DRAIN_LOCK_PATH, claimed);
        try { unlinkSync(claimed); } catch (_err) { void 0; /* best-effort */ }
    } catch (_err) { void 0; /* another owner or an already-released lease */ }
}

