import { describe, expect, it } from "vitest";
import { classifyByContent, markerEvidence, shapeEvidence } from "./role-evidence-content.js";

describe("self-declared generator banners in the first lines", () => {
	// MUST-CLASSIFY
	it.each([
		["// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n"],
		["/* @generated */\nexport const a = 1;\n"],
		["/**\n * @generated SignedSource<<abc>>\n */\nexport const a = 1;\n"],
		["// AUTO-GENERATED by scripts/generate_framework_mappings.py\nexport default {};\n"],
		["//! GENERATED by rust/scripts/gen-oids.ts from oids.ts\n//! Do not edit by hand\npub fn a() {}\n"],
		["# Generated by the protocol buffer compiler.  DO NOT EDIT!\nimport sys\n"],
		["// This file was automatically generated by TanStack Router.\nexport const a = 1;\n"],
		["# This file is autogenerated\nx = 1\n"],
		["/* @codegen-data — table of ids */\nexport const ids = [];\n"],
		["#!/usr/bin/env node\n// @generated\nconsole.log(1);\n"],
		["/*\n   This file is auto-generated.\n*/\nexport const a = 1;\n"],
		// OpenAPI Generator (TypeScript): block comment with "auto generated" and "Do not edit the class manually."
		["/* tslint:disable */\n/**\n * API\n * No description provided (generated by Openapi Generator https://github.com/openapitools/openapi-generator)\n *\n * NOTE: This class is auto generated by OpenAPI Generator (https://openapi-generator.tech).\n * Do not edit the class manually.\n */\nexport const a = 1;\n"],
		// OpenAPI Generator (Python): the banner is in the module docstring, below a license comment
		[`${"# license line\n".repeat(9)}\n"""\nAdmin API\n\nGenerated by OpenAPI Generator (https://openapi-generator.tech)\n\nDo not edit the class manually.\n"""\nimport os\n`],
		// orval
		["/**\n * Generated by orval v7 🍺\n * Do not edit manually.\n */\nexport type A = string;\n"],
	])("marks a self-declared generated file: %j", content => {
		expect(markerEvidence(content)).toMatchObject({ kind: "marker" });
		expect(markerEvidence(content)?.detail).toMatch(/^line \d+: /);
	});
	// MUST-NOT-CLASSIFY
	it.each([
		["export const a = 1;\n".repeat(12) + "// DO NOT EDIT\n"],
		["export const note = \"do not edit\";\n"],
		["export const generated = true;\n"],
		["// Generated IDs are stable across runs.\nexport const a = 1;\n"],
		["// Handles auto-generated ids for new rows.\nexport const a = 1;\n"],
		["// Do not edit the order of these cases; they run in sequence.\nexport const a = 1;\n"],
		["// Regenerate with npm run build when the schema changes.\nexport const a = 1;\n"],
		["/* The generator below is hand written. */\nexport function generate() {}\n"],
		// Found on a real file: a doc comment that names the tag in the middle of a sentence.
		["/** Generator banners. The tag `@generated` is a convention of many tools. */\nexport const a = 1;\n"],
		["//   - `@codegen-data` (this repository's carriers), and\nexport const a = 1;\n"],
		["//     (`@generated`, \"Code generated … DO NOT EDIT.\", \"auto-generated\", …).\nexport const a = 1;\n"],
		// Banner text inside a string literal or a docstring that opens after code is not a header.
		["import os\n\nX = \"\"\"\nGenerated by OpenAPI Generator\nDo not edit the class manually.\n\"\"\"\n"],
		["import os\nBANNER = 'This class is auto generated by a tool'\n"],
		// A hand-written module docstring that only talks about generation.
		["\"\"\"Helpers that generate ids.\n\nThe generator is hand written.\n\"\"\"\nimport os\n"],
		["// Documents the banner \"DO NOT EDIT\" that tools write.\nexport const a = 1;\n"],
		["// Auto-extracted from hooks.ts by the sweep refactor. @codegen-data: template DATA\nexport const a = 1;\n"],
	])("keeps a hand-written file authored: %j", content => {
		expect(markerEvidence(content)).toBeNull();
	});
	it("ignores a banner that only appears after the first ten lines", () => {
		const content = `${"// line\n".repeat(10)}// @generated\nexport const a = 1;\n`;
		expect(markerEvidence(content)).toBeNull();
	});
	it("reports the line of the banner", () => {
		expect(markerEvidence("// header\n// @generated\n")?.detail).toBe("line 2: @generated");
	});
});

describe("minified or bundled code, judged from line statistics (calibration: see role-evidence-content.ts)", () => {
	const code = "var f=function(a,b){return a+b},x=f(1,2),y=f(x,3);";
	// MUST-CLASSIFY
	it("marks a one-line minified bundle", () => {
		const content = `${code.repeat(600)}\n`;
		expect(shapeEvidence(content)).toMatchObject({ kind: "shape" });
		expect(shapeEvidence(content)?.detail).toMatch(/^mean line [\d.]+ chars, space share 0\.\d+, \(\) share 0\.\d+$/);
	});
	it("marks a bundle of a few very long lines", () => {
		expect(shapeEvidence(`${code.repeat(300)}\n${code.repeat(300)}\n${code.repeat(300)}\n`)).not.toBeNull();
	});
	it("marks a bundle of 2000 lines of about 2000 characters", () => {
		const line = `${"let a=e=>{if(e)throw e;return t(e)},b=(n,r)=>r.map(i=>n(i));".repeat(33)}\n`;
		expect(shapeEvidence(line.repeat(2000))).not.toBeNull();
	});
	it("marks minified code whose lines are only about 500 characters long", () => {
		const line = `${"var f=function(a,b){return a+b},x=f(1,2),y=f(x,3);".repeat(13)}\n`;
		expect(shapeEvidence(line.repeat(30))).not.toBeNull();
	});
	it("marks minified CSS", () => {
		expect(shapeEvidence(`${".a{color:rgba(0,0,0,.5);margin:calc(1px+2px)}".repeat(400)}\n`)).not.toBeNull();
	});
	it("keeps an SVG export authored: Inkscape style attributes carry many `;` and almost no parentheses", () => {
		const path = '<path style="fill:#ffffff;stroke:#000000;stroke-width:0.5;fill-opacity:1" d="M 10,20 C 30,40 50,60 70,80"/>';
		expect(shapeEvidence(`${path.repeat(150)}\n`)).toBeNull();
	});
	it("keeps source code held in template strings authored (many parentheses, but spaces and short lines like real code)", () => {
		const line = "    const value = compute(first, second) + helper(third, fourth) - other(fifth);\n";
		expect(shapeEvidence(line.repeat(300))).toBeNull();
		expect(shapeEvidence(`const template = \`${line.repeat(300).replaceAll("\n", " ")}\`;\n`)).toBeNull();
	});
	it("reads a quote inside a comment as nothing: no string parsing is involved", () => {
		expect(shapeEvidence(`// don't\n${code.repeat(600)}\n`)).not.toBeNull();
	});
	// MUST-NOT-CLASSIFY
	it("keeps a file with one very long string literal authored", () => {
		expect(shapeEvidence(`export const image = "data:image/png;base64,${"QUJD".repeat(20000)}";\n`)).toBeNull();
	});
	it("keeps a file of long inline SVG data authored", () => {
		const row = `export const icon = "<svg viewBox='0 0 10 10'>${"<path d='M1 2L3 4Z'/>".repeat(100)}</svg>";\n`;
		expect(shapeEvidence(row.repeat(6))).toBeNull();
	});
	it("keeps a file with one very long comment line authored (found on this repository's own inventory test)", () => {
		expect(shapeEvidence(`// ${"x".repeat(2 * 1024 * 1024)}\nexport function atEnd(enabled: boolean) { return enabled ? 1 : 0; }\n`)).toBeNull();
		expect(shapeEvidence(`/* ${"x ".repeat(20000)} */\nexport const a = 1;\n`)).toBeNull();
	});
	it("keeps a one-line data table authored without parentheses", () => {
		expect(shapeEvidence(`export const T = {${'"launch":{"title":"Course","tags":["a","b"],"n":12},'.repeat(400)}};\n`)).toBeNull();
	});
	it("keeps one-line minified JSON authored (a data file, with no code punctuation)", () => {
		expect(shapeEvidence(`{${'"k":{"a":1,"b":[1,2,3]},'.repeat(800)}"z":0}\n`)).toBeNull();
	});
	it("keeps a one-line CJK translation table authored (no spaces, no code punctuation)", () => {
		expect(shapeEvidence(`export default {${'"键":"汉字汉字汉字汉字",'.repeat(800)}};\n`)).toBeNull();
	});
	it("keeps long prose lines authored (many spaces)", () => {
		expect(shapeEvidence(`${"The quick brown fox (a story); it jumps over the lazy dog and keeps running. ".repeat(10)}\n`.repeat(30))).toBeNull();
	});
	it("keeps a generated SVG animation component authored (SMIL attributes carry `;` and `(`)", () => {
		const svg = '<polygon class="ln" points="-121.2,70.0 121.2,210.0"/><g opacity="0"><animate attributeName="opacity" values="0;1;0;1" dur="4s"/></g>';
		expect(shapeEvidence(`${svg.repeat(120)}\n`)).toBeNull();
	});
	it("keeps binary content authored (a NUL byte means it is not text)", () => {
		expect(shapeEvidence(`\0${code.repeat(600)}\n`)).toBeNull();
	});
	it("keeps ordinary dense hand-written code authored (short lines)", () => {
		expect(shapeEvidence("export function f(a: number, b: number): number { return a + b; }\n".repeat(400))).toBeNull();
	});
	it("keeps a long hand-written data table authored", () => {
		expect(shapeEvidence("  { id: 'a-1', title: 'Control', parent: 'a' },\n".repeat(5000))).toBeNull();
	});
	it("keeps a normal file with one long line authored", () => {
		expect(shapeEvidence(`${"const a = 1;\n".repeat(400)}const long = [${"1,".repeat(1500)}];\n`)).toBeNull();
	});
	it("keeps a small file authored", () => {
		expect(shapeEvidence(`${code.repeat(20)}\n`)).toBeNull();
	});
});

describe("content classification sets aside by structure only; a header never does", () => {
	it("reports shape, also when a header is present", () => {
		const content = `// @generated\n${"var f=function(a,b){return a+b},x=f(1,2),y=f(x,3);".repeat(600)}\n`;
		expect(classifyByContent(content)).toMatchObject({ role: "generated", evidence: { kind: "shape" } });
	});
	it("a banner outside the header position is reported as declared, not acted on", () => {
		expect(classifyByContent("export const a = 1;\n// @generated\n")).toBeNull();
		expect(markerEvidence("export const a = 1;\n// @generated\n")).toEqual({ kind: "marker", detail: "line 2: @generated" });
	});
	it("returns null for ordinary source", () => {
		expect(classifyByContent("export const a = 1;\n")).toBeNull();
	});
});
