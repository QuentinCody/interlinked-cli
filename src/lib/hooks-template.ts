function sanitizeAgentName(value) {
    if (typeof value !== "string") return null;
    const trimmed = value.trim();
    if (!trimmed) return null;
    if (trimmed.toLowerCase() === "unknown") return null;
    return trimmed.slice(0, 80);
}

function readSessionAgent(sessionId) {
    if (!sessionId) return null;
    try {
        const sessionPath = safeSessionFilePath(sessionId, ".json");
        if (!sessionPath) return null;
        if (!existsSync(sessionPath)) return null;
        const session = JSON.parse(readFileSync(sessionPath, "utf-8"));
        return sanitizeAgentName(session?.agent);
    } catch {
        return null;
    }
}

function extractAgentName(rawInput, event) {
    const candidates = [
        rawInput?.agent_name,
        rawInput?.agentName,
        rawInput?.parent_agent_name,
        rawInput?.parentAgentName,
        rawInput?.sender_name,
        rawInput?.senderName,
        rawInput?.agent?.name,
        event?.parent_agent,
    ];
    for (const candidate of candidates) {
        const normalized = sanitizeAgentName(candidate);
        if (normalized) return normalized;
    }
    return null;
}

function buildSessionAgent(clientName, sessionId) {
    const sid = typeof sessionId === "string" && sessionId.length > 0
        ? sessionId.replace(/[^a-zA-Z0-9]/g, "").slice(0, 8)
        : "global";
    const normalizedClient = sanitizeAgentName(clientName || "") || "agent";
    return ("session-" + normalizedClient.toLowerCase() + "-" + sid).slice(0, 80);
}

function resolveAgentName(config, rawInput, event, clientName, sessionId) {
    const configured = sanitizeAgentName(config?.agent_name);
    if (configured) return configured;

    const discovered = extractAgentName(rawInput, event);
    if (discovered) return discovered;

    const existingSessionAgent = readSessionAgent(sessionId);
    if (existingSessionAgent) return existingSessionAgent;

    return buildSessionAgent(clientName, sessionId);
}

