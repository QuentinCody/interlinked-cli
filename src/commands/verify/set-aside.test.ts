import { mkdtempSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { classifySetAside } from "./set-aside.js";

function minified(chars: number): string {
	// One long line of calls with almost no spaces: the shape evidence of a bundle.
	return `${"f(a,b);g(c(d),e(f));".repeat(Math.ceil(chars / 20))}\n`;
}

describe("classifySetAside — positive (set aside)", () => {
	it("P1: a minified bundle is generated by shape evidence", () => {
		const root = mkdtempSync(join(tmpdir(), "setaside-"));
		const out = classifySetAside(root, join(root, "assets/chart-abc.js"), minified(40_000));
		expect(out?.role).toBe("generated");
		expect(out?.evidence_kind).toBe("shape");
		expect(out?.bytes).toBe(Buffer.byteLength(minified(40_000)));
	});
	it("P2: a *.min.js file is vendor by tool-path evidence, whatever its shape", () => {
		const root = mkdtempSync(join(tmpdir(), "setaside-"));
		const out = classifySetAside(root, join(root, "site/app.min.js"), "var a = 1;\n");
		expect(out?.role).toBe("vendor");
		expect(out?.evidence_kind).toBe("tool-path");
	});
	it("P3: a file under third_party is vendor by path evidence", () => {
		const root = mkdtempSync(join(tmpdir(), "setaside-"));
		mkdirSync(join(root, "third_party"), { recursive: true });
		const out = classifySetAside(root, join(root, "third_party/lib.js"), "var a = 1;\n");
		expect(out?.role).toBe("vendor");
	});
});

describe("classifySetAside — negative (kept)", () => {
	it("N1: an ordinary hand-written source file is kept", () => {
		const root = mkdtempSync(join(tmpdir(), "setaside-"));
		expect(classifySetAside(root, join(root, "src/app.ts"), "export const a = 1;\nexport const b = 2;\n")).toBeNull();
	});
	it("N2: a long file with ordinary line lengths is kept", () => {
		const root = mkdtempSync(join(tmpdir(), "setaside-"));
		const text = "const value = compute(first, second);\n".repeat(2000);
		expect(classifySetAside(root, join(root, "src/long.ts"), text)).toBeNull();
	});
	it("N3: a test file is kept", () => {
		const root = mkdtempSync(join(tmpdir(), "setaside-"));
		writeFileSync(join(root, "a.test.ts"), "");
		expect(classifySetAside(root, join(root, "a.test.ts"), "it('x', () => {});\n")).toBeNull();
	});
});
