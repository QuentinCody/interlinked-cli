// ===========================================

function generateStructuralChecks(): string {
	const lines: string[] = [
		"<!-- Auto-generated by scripts/generate-docs.ts — do not edit manually -->",
		"# Structural Checks Reference",
		"",
		`${Object.keys(STRUCTURAL_CHECK_META).length} dependency-aware checks that run after file edits.`,
		"These analyze the project graph to detect cross-file issues that single-file lint can't catch.",
		"",
	];

	// Group by tier
	const byTier = new Map<number, [string, (typeof STRUCTURAL_CHECK_META)[string]][]>();
	for (const [key, meta] of Object.entries(STRUCTURAL_CHECK_META)) {
		if (!byTier.has(meta.tier)) byTier.set(meta.tier, []);
		byTier.get(meta.tier)!.push([key, meta]);
	}

	const tierLabels: Record<number, string> = {
		1: "Tier 1 — Fast (sub-100ms, every edit)",
		2: "Tier 2 — Medium (sub-1s, every edit)",
		3: "Tier 3 — Conditional (1-5s, only when needed)",
	};

	for (const tier of [1, 2, 3]) {
		const checks = byTier.get(tier);
		if (!checks || checks.length === 0) continue;

		lines.push(`## ${tierLabels[tier]}`);
		lines.push("");
		lines.push("| Check | Config Key | Description |");
		lines.push("|-------|-----------|-------------|");

		for (const [key, meta] of checks) {
			lines.push(`| ${meta.name} | \`${key}\` | ${meta.description} |`);
		}
		lines.push("");
	}

	return lines.join("\n");
}

