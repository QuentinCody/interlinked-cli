// Companion test for exemption-marker-budget.ts: the executable-code view and
// the branch budget that decides whether a generated-file marker exempts a file.
import { describe, expect, it } from "vitest";

import {
	branchTokenCount,
	CODEGEN_DATA_BRANCH_BUDGET,
	codegenDataMarkerDenial,
	executableCodeView,
	generatorMarkerDenial,
	isCodegenDataModule,
	isHonoredGeneratedFile,
} from "./exemption-marker-budget.js";

describe("executableCodeView — positive (must keep code visible)", () => {
	it("P1: code inside a template interpolation stays visible; template text is blanked", () => {
		const src = "const s = `if text ${a ? b : c} for text`;\n";
		const view = executableCodeView(src, "x.ts");
		expect(view).toHaveLength(src.length);
		expect(view).toContain("a ? b : c");
		expect(view).not.toContain("if text");
		expect(view).not.toContain("for text");
	});

	it("P2: nested templates inside an interpolation are lexed recursively at any depth", () => {
		const src = "const s = `${`${`${`${x && y}`}`}`}`;\n";
		expect(branchTokenCount(src, "x.ts")).toBe(1);
		const textInside = "const s = `${`if ${p || q} while`}`;\n";
		const view = executableCodeView(textInside, "x.ts");
		expect(view).toContain("p || q");
		expect(view).not.toContain("while");
	});

	it("P3: an unterminated template fails closed — its whole tail is counted as code", () => {
		const src = "const s = `text ${x}\nif (a) {}\nwhile (b) {}\n";
		expect(branchTokenCount(src, "x.ts")).toBe(2);
	});

	it("P4: a TS non-null `x! / y` is division, so a later `/` cannot open a regex that hides code", () => {
		const src = "const r = x! / 2; if (a) f(); if (b) g(); const z = 1 / 3;\n";
		expect(branchTokenCount(src, "x.ts")).toBe(2);
	});

	it("P5: Python — an f-string disables blanking (its fields are executable)", () => {
		const src = '# @generated\nX = f"{a if b else c}"\n';
		expect(executableCodeView(src, "gen.py")).toBe(src);
	});

	it("P6: a language with no lexer is counted raw", () => {
		const src = "// for if while\n";
		expect(executableCodeView(src, "x.go")).toBe(src);
	});
});

describe("executableCodeView — negative (must blank data)", () => {
	it("N1: strings, comments and regex literals are blanked, offsets preserved", () => {
		const src = 'const a = "if"; // while\nconst r = /for|case/g; /* do */\n';
		const view = executableCodeView(src, "x.ts");
		expect(view).toHaveLength(src.length);
		expect(branchTokenCount(src, "x.ts")).toBe(0);
		expect(view.split("\n")).toHaveLength(src.split("\n").length);
	});

	it("N2: Python comments and triple-quoted strings are blanked", () => {
		const src = '# if for while\nDOC = """\nif x:\n    for y in z: pass\n"""\nT = {"a": \'or\'}\n';
		expect(branchTokenCount(src, "data.py")).toBe(0);
	});

	it("N3: a simple `${a.b}` property interpolation carries no branch", () => {
		const src = "export const T = `head ${cfg.mode} mid ${cfg.name} tail`;\n";
		expect(branchTokenCount(src, "x.ts")).toBe(0);
	});
});

describe("marker denials — positive (must refuse)", () => {
	it("P7: every generator header is refused once the budget is exceeded", () => {
		const body = "export const v = a ? b : c ? d : e ? f : g;\n";
		expect(generatorMarkerDenial(`// @generated\n${body}`, "x.ts")).toContain("refused");
		expect(generatorMarkerDenial(`// Code generated by tool. DO NOT EDIT.\n${body}`, "x.ts")).toContain("refused");
		expect(generatorMarkerDenial(`// auto-generated\n${body}`, "x.ts")).toContain("refused");
		expect(isHonoredGeneratedFile(`// @generated\n${body}`, "x.ts")).toBe(false);
		expect(codegenDataMarkerDenial(`// @codegen-data\n${body}`)).toContain("@codegen-data refused");
	});
});

describe("marker denials — negative (must honour data)", () => {
	it("N4: branch-free generated data and a ${preset} carrier stay honoured", () => {
		const data = `// @generated\nexport const ROWS = [\n${'\t{ id: 1, name: "for" },\n'.repeat(50)}];\n`;
		expect(isHonoredGeneratedFile(data, "x.ts")).toBe(true);
		const carrier = "// @codegen-data\nexport const render = (preset: string) => `if (x) ${preset}`;\n";
		expect(isCodegenDataModule(carrier)).toBe(true);
		expect(generatorMarkerDenial("export const x = a ? b : c ? d : e;\n", "x.ts")).toBeNull();
		expect(CODEGEN_DATA_BRANCH_BUDGET).toBe(2);
	});
});
