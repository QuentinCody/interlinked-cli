import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import {
	describeLockfilePackage,
	nativeEvidenceOnDisk,
	newLockfilePackages,
	parseLockfilePackages,
	readLockfileSnapshot,
} from "./lockfile-packages.js";

/** The Hegel-trial shape: a command-line dep (`koffi`) whose optional
 *  platform dep (`@koromix/koffi-darwin-arm64`) never met the install gate. */
const KOFFI_LOCK = JSON.stringify({
	name: "trial",
	lockfileVersion: 3,
	packages: {
		"": { name: "trial", dependencies: { koffi: "3.3.2" } },
		"node_modules/koffi": { version: "3.3.2", hasInstallScript: true },
		"node_modules/@koromix/koffi-darwin-arm64": {
			version: "3.3.2",
			cpu: ["arm64"],
			optional: true,
			os: ["darwin"],
		},
		"node_modules/@hegeldev/hegel": { version: "0.4.7" },
		"node_modules/@hegeldev/hegel/node_modules/nested-dep": { version: "1.0.0" },
	},
});

describe("parseLockfilePackages — positive (must inventory)", () => {
	it("P1: package-lock v3 names every node_modules entry, nested paths included, with native evidence", () => {
		const inv = parseLockfilePackages("package-lock.json", KOFFI_LOCK);
		expect(inv).not.toBeNull();
		expect([...inv!.keys()].sort()).toEqual(
			["@hegeldev/hegel", "@koromix/koffi-darwin-arm64", "koffi", "nested-dep"].sort(),
		);
		expect(inv!.get("koffi")).toEqual({ name: "koffi", version: "3.3.2", native: ["install script"] });
		expect(inv!.get("@koromix/koffi-darwin-arm64")?.native).toEqual([
			"platform package (os darwin, cpu arm64)",
			"optionalDependency",
		]);
		expect(inv!.get("@hegeldev/hegel")?.native).toEqual([]);
	});

	it("P2: package-lock v1 walks the nested dependencies tree", () => {
		const v1 = JSON.stringify({
			lockfileVersion: 1,
			dependencies: {
				a: { version: "1.0.0", dependencies: { b: { version: "2.0.0", optional: true } } },
			},
		});
		const inv = parseLockfilePackages("package-lock.json", v1);
		expect([...inv!.keys()].sort()).toEqual(["a", "b"]);
		expect(inv!.get("b")?.native).toEqual(["optionalDependency"]);
	});

	it("P3: pnpm-lock v9 reads packages + snapshots and the requiresBuild / os / cpu markers", () => {
		const pnpm = [
			"lockfileVersion: '9.0'",
			"",
			"importers:",
			"  .:",
			"    dependencies:",
			"      koffi:",
			"        specifier: 3.3.2",
			"        version: 3.3.2",
			"",
			"packages:",
			"",
			"  '@koromix/koffi-darwin-arm64@3.3.2':",
			"    resolution: {integrity: sha512-abc}",
			"    cpu: [arm64]",
			"    os: [darwin]",
			"",
			"  koffi@3.3.2:",
			"    resolution: {integrity: sha512-def}",
			"    requiresBuild: true",
			"",
			"  plain@1.0.0:",
			"    resolution: {integrity: sha512-ghi}",
			"",
			"snapshots:",
			"",
			"  '@koromix/koffi-darwin-arm64@3.3.2':",
			"    optional: true",
			"",
			"  koffi@3.3.2:",
			"    optionalDependencies:",
			"      '@koromix/koffi-darwin-arm64': 3.3.2",
			"",
			"  plain@1.0.0: {}",
		].join("\n");
		const inv = parseLockfilePackages("pnpm-lock.yaml", pnpm);
		expect([...inv!.keys()].sort()).toEqual(["@koromix/koffi-darwin-arm64", "koffi", "plain"]);
		expect(inv!.get("koffi")).toEqual({ name: "koffi", version: "3.3.2", native: ["install script"] });
		expect(inv!.get("@koromix/koffi-darwin-arm64")?.native).toEqual([
			"platform package (name)",
			"platform package (cpu constraint)",
			"platform package (os constraint)",
			"optionalDependency",
		]);
		expect(inv!.get("plain")?.native).toEqual([]);
	});

	it("P4: yarn v1 and berry headers both yield the package name and version", () => {
		const v1 = [
			"# THIS IS AN AUTOGENERATED FILE.",
			"# yarn lockfile v1",
			"",
			'"@scope/pkg@^1.0.0", "@scope/pkg@^1.2.0":',
			'  version "1.2.3"',
			"",
			"plain@~2.0.0:",
			'  version "2.0.1"',
		].join("\n");
		const berry = [
			"__metadata:",
			"  version: 8",
			"",
			'"left-pad@npm:^1.3.0":',
			"  version: 1.3.0",
			'  resolution: "left-pad@npm:1.3.0"',
		].join("\n");
		expect([...parseLockfilePackages("yarn.lock", v1)!.entries()].map(([n, p]) => `${n}@${p.version}`)).toEqual([
			"@scope/pkg@1.2.3",
			"plain@2.0.1",
		]);
		expect(parseLockfilePackages("yarn.lock", berry)!.get("left-pad")?.version).toBe("1.3.0");
	});

	it("P5: bun.lock (JSONC with trailing commas) names packages and platform metadata", () => {
		const bun = [
			"{",
			'  "lockfileVersion": 1,',
			'  "packages": {',
			'    "koffi": ["koffi@3.3.2", "", { "optionalDependencies": { "@koromix/koffi-darwin-arm64": "3.3.2" } }, "sha512-x"],',
			'    "@koromix/koffi-darwin-arm64": ["@koromix/koffi-darwin-arm64@3.3.2", "", { "os": "darwin", "cpu": "arm64" }, "sha512-y"],',
			"  },",
			"}",
		].join("\n");
		const inv = parseLockfilePackages("bun.lock", bun);
		expect(inv!.get("koffi")?.version).toBe("3.3.2");
		expect(inv!.get("@koromix/koffi-darwin-arm64")?.native).toEqual([
			"platform package (os darwin, cpu arm64)",
		]);
	});

	it("P6: the platform-name convention is evidence even when the lockfile carries no os/cpu field", () => {
		const yarn = `# yarn lockfile v1\n\n"@biomejs/cli-linux-x64-musl@2.0.0":\n  version "2.0.0"\n`;
		expect(parseLockfilePackages("yarn.lock", yarn)!.get("@biomejs/cli-linux-x64-musl")?.native).toEqual([
			"platform package (name)",
		]);
	});
});

describe("parseLockfilePackages — negative (must refuse, never invent)", () => {
	it("N1: an unknown basename is null", () => {
		expect(parseLockfilePackages("Cargo.lock", "[[package]]")).toBeNull();
	});

	it("N2: malformed JSON / a shape without packages or dependencies is null", () => {
		expect(parseLockfilePackages("package-lock.json", "{ nope")).toBeNull();
		expect(parseLockfilePackages("package-lock.json", '{"lockfileVersion": 3}')).toBeNull();
		expect(parseLockfilePackages("bun.lock", '{"lockfileVersion": 1}')).toBeNull();
	});

	it("N3: a YAML file without a packages: section and a yarn file without a header are null", () => {
		expect(parseLockfilePackages("pnpm-lock.yaml", "lockfileVersion: '9.0'\nimporters: {}\n")).toBeNull();
		expect(parseLockfilePackages("yarn.lock", "foo@1:\n  version 1\n")).toBeNull();
	});

	it("N4: the root entry and workspace links are not packages", () => {
		const lock = JSON.stringify({
			lockfileVersion: 3,
			packages: { "": { name: "root" }, "packages/app": { version: "0.0.0" } },
		});
		expect(parseLockfilePackages("package-lock.json", lock)!.size).toBe(0);
	});
});

describe("newLockfilePackages", () => {
	it("P7: returns exactly the names absent from the baseline — the transitive native dep included", () => {
		const before = parseLockfilePackages(
			"package-lock.json",
			JSON.stringify({ lockfileVersion: 3, packages: { "": {}, "node_modules/@hegeldev/hegel": { version: "0.4.6" } } }),
		)!;
		const after = parseLockfilePackages("package-lock.json", KOFFI_LOCK)!;
		expect(newLockfilePackages(before, after).map((p) => p.name).sort()).toEqual(
			["@koromix/koffi-darwin-arm64", "koffi", "nested-dep"].sort(),
		);
	});

	it("N5: a version bump of a package already present is not NEW", () => {
		const before = new Map([["a", { name: "a", version: "1.0.0", native: [] }]]);
		const after = new Map([["a", { name: "a", version: "2.0.0", native: [] }]]);
		expect(newLockfilePackages(before, after)).toEqual([]);
	});
});

describe("readLockfileSnapshot + nativeEvidenceOnDisk", () => {
	let dir: string;
	beforeEach(() => {
		dir = mkdtempSync(join(tmpdir(), "lockfile-packages-"));
	});
	afterEach(() => {
		rmSync(dir, { recursive: true, force: true });
	});

	it("P8: no lockfile ⇒ an EMPTY snapshot (file null), not null", () => {
		expect(readLockfileSnapshot(dir)).toEqual({ file: null, packages: new Map() });
	});

	it("P9: the first present lockfile is read; a parse failure is null", () => {
		writeFileSync(join(dir, "package-lock.json"), KOFFI_LOCK);
		expect(readLockfileSnapshot(dir)?.file).toBe("package-lock.json");
		expect(readLockfileSnapshot(dir)?.packages.has("koffi")).toBe(true);
		writeFileSync(join(dir, "package-lock.json"), "{ broken");
		expect(readLockfileSnapshot(dir)).toBeNull();
	});

	it("P10: on-disk evidence — binding.gyp, install-phase scripts, a .node binary", () => {
		const pkg = join(dir, "node_modules", "@koromix", "koffi-darwin-arm64");
		mkdirSync(join(pkg, "build", "Release"), { recursive: true });
		writeFileSync(join(pkg, "binding.gyp"), "{}");
		writeFileSync(join(pkg, "package.json"), JSON.stringify({ scripts: { install: "node cnoke.cjs", test: "x" } }));
		writeFileSync(join(pkg, "build", "Release", "koffi.node"), "");
		expect(nativeEvidenceOnDisk(dir, "@koromix/koffi-darwin-arm64")).toEqual([
			"binding.gyp",
			"install script (install)",
			".node binary",
		]);
	});

	it("N6: an uninstalled or plain package has no on-disk evidence", () => {
		expect(nativeEvidenceOnDisk(dir, "absent")).toEqual([]);
		const pkg = join(dir, "node_modules", "plain");
		mkdirSync(pkg, { recursive: true });
		writeFileSync(join(pkg, "package.json"), JSON.stringify({ scripts: { test: "x" } }));
		writeFileSync(join(pkg, "index.js"), "");
		expect(nativeEvidenceOnDisk(dir, "plain")).toEqual([]);
	});

	it("P11: describeLockfilePackage marks native packages loudly and merges extra evidence once", () => {
		expect(describeLockfilePackage({ name: "a", version: "1.0.0", native: [] })).toBe("a@1.0.0");
		expect(describeLockfilePackage({ name: "a", version: null, native: [] })).toBe("a");
		expect(
			describeLockfilePackage({ name: "koffi", version: "3.3.2", native: ["install script"] }, [
				"install script",
				".node binary",
			]),
		).toBe("koffi@3.3.2 [NATIVE: install script; .node binary]");
	});
});
