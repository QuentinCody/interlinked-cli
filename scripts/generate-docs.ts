// ===========================================

function generateGuardRules(): string {
	const rules = getBuiltinRules();
	const lines: string[] = [
		"<!-- Auto-generated by scripts/generate-docs.ts — do not edit manually -->",
		"# Guard Rules Reference",
		"",
		`${rules.length} built-in rules that block or warn on dangerous operations.`,
		"These evaluate on every PreToolUse event (before tool execution).",
		"",
	];

	// Group by category
	const byCategory = new Map<string, typeof rules>();
	for (const rule of rules) {
		const cat = (rule as { category?: string }).category || "uncategorized";
		if (!byCategory.has(cat)) byCategory.set(cat, []);
		byCategory.get(cat)!.push(rule);
	}

	// Sort categories for stable output
	const sortedCategories = [...byCategory.keys()].sort();

	for (const cat of sortedCategories) {
		const catRules = byCategory.get(cat)!;
		const displayName = cat
			.split("-")
			.map((w) => w.charAt(0).toUpperCase() + w.slice(1))
			.join(" ");

		lines.push(`## ${displayName}`);
		lines.push("");
		lines.push("| Rule | Severity | Action | Description |");
		lines.push("|------|----------|--------|-------------|");

		for (const rule of catRules) {
			const suggestion = rule.suggestion ? ` ${rule.suggestion}` : "";
			lines.push(
				`| \`${rule.id}\` | ${rule.severity} | ${rule.action} | ${rule.reason}${suggestion} |`,
			);
		}
		lines.push("");
	}

	return lines.join("\n");
}

// ===========================================
// Quality Checks Reference
// ===========================================

function generateQualityChecks(): string {
	const config = getDefaultConfig();
	const checks = config.quality_checks;

	const lines: string[] = [
		"<!-- Auto-generated by scripts/generate-docs.ts — do not edit manually -->",
		"# Quality Checks Reference",
		"",
		`${Object.keys(checks).length} PostToolUse checks that run after file edits.`,
		"Subprocess-based checks run external tools (tsc, biome, etc.); inline checks scan file content directly.",
		"",
		"| Check | Severity | File Types | Description |",
		"|-------|----------|------------|-------------|",
	];

	for (const [name, check] of Object.entries(checks)) {
		const types = check.file_types.slice(0, 5).join(", ");
		const overflow = check.file_types.length > 5 ? " ..." : "";
		const desc = check.description || name;
		const kind = check.command ? "subprocess" : "inline";
		lines.push(
			`| \`${name}\` (${kind}) | ${check.severity} | ${types}${overflow} | ${desc} |`,
		);
	}

	lines.push("");
	return lines.join("\n");
}

