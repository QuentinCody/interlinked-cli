import { describe, expect, it } from "vitest";
import { refineInventory, SCORE_ROLES_VERSION } from "./inventory-refine.js";
import { hashBytes, inventoryHash } from "./inventory.js";
import { sourceLanguage, sourceRole } from "./inventory-roles.js";
import type { RepositoryInventory } from "./measurement-types.js";

function inventory(sources: Record<string, string>): RepositoryInventory {
	const files = Object.entries(sources).map(([path, content]) => ({ path, content, language: sourceLanguage(path), role: sourceRole(path), sha256: hashBytes(content) }));
	return { version: "interlinked-source-roles-v4", root: "/nowhere", discovery: "git", files, gaps: [{ path: "src/unreadable.ts", role: "product", reason: "ENOENT" }],
		excluded: [{ path: "dist/out.js", role: "generated", reason: "Excluded by source-role policy" }], issues: ["note"],
		inputHash: inventoryHash(files), sourceHash: inventoryHash(files.filter(file => file.role === "product")) };
}
const minified = "var f=function(a,b){return a+b},x=f(1,2),y=f(x,3);".repeat(600);

describe("score-report inventory refinement (roles v5)", () => {
	const raw = inventory({
		"src/authored.ts": "export const a = 1;\n",
		"src/declared.ts": "export const first = 1;\n// AUTO-GENERATED by scripts/gen.py\nexport const b = 1;\n",
		"src/header.ts": "// AUTO-GENERATED by scripts/gen.py\nexport const h = 1;\n",
		"src/hand.ts": "// Generated IDs are stable.\nexport const c = 1;\n",
		"src/input_gen.ts": "export const d = 1;\n",
		".yarn/releases/yarn.cjs": "module.exports = 1;\n",
		"api/user.pb.ts": "export const e = 1;\n",
		"web/bundle.js": `${minified}\n`,
		"web/image.ts": `export const image = "data:image/png;base64,${"QUJD".repeat(20000)}";\n`,
		"mocks/orders.ts": "export const orders = [1, 2, 3];\n",
		"src/authored.test.ts": "// @generated\nexport {};\n",
		"README.md": "# docs\n",
	});
	const refined = refineInventory(raw);

	it("keeps authored files, the hand-written look-alikes and tests as they were", () => {
		const roles = Object.fromEntries(refined.files.map(file => [file.path, file.role]));
		expect(roles).toMatchObject({ "src/authored.ts": "product", "src/hand.ts": "product", "src/input_gen.ts": "product", "web/image.ts": "product",
			"src/authored.test.ts": "test", "README.md": "documentation" });
	});
	it("sets aside generated and vendored files with the kind of evidence for each", () => {
		const aside = Object.fromEntries(refined.excluded.filter(file => file.from !== undefined).map(file => [file.path, [file.role, file.evidence?.kind]]));
		expect(aside).toEqual({ ".yarn/releases/yarn.cjs": ["vendor", "tool-path"], "api/user.pb.ts": ["generated", "path"], "src/header.ts": ["generated", "marker"], "web/bundle.js": ["generated", "shape"] });
		expect(refined.files.map(file => file.path)).not.toContain("web/bundle.js");
	});
	it("keeps a file that only declares itself generated a measured product, labelled as declared", () => {
		expect(refined.files.find(file => file.path === "src/declared.ts")).toMatchObject({ role: "product", declaredGenerated: { detail: "line 2: AUTO-GENERATED by" } });
		expect(refined.excluded.some(file => file.path === "src/declared.ts")).toBe(false);
		expect(refined.files.find(file => file.path === "src/hand.ts")?.declaredGenerated).toBeUndefined();
	});
	it("does not label a test file, which no header moves or reports", () => {
		expect(refined.files.find(file => file.path === "src/authored.test.ts")?.declaredGenerated).toBeUndefined();
	});
	it("keeps a moved file measured as a test, with where it came from", () => {
		expect(refined.files.find(file => file.path === "mocks/orders.ts")).toMatchObject({ role: "test", moved: { from: "product", evidence: { kind: "path", detail: "mocks/" } } });
	});
	it("records the line count of a file it read before setting it aside", () => {
		expect(refined.excluded.find(file => file.path === "web/bundle.js")?.lines).toBe(1);
	});
	it("keeps existing exits, gaps, issues, root and the raw census hashes, and states the v5 version", () => {
		expect(refined.excluded.find(file => file.path === "dist/out.js")).toEqual(raw.excluded[0]);
		expect(refined.gaps).toEqual(raw.gaps);
		expect(refined.issues).toEqual(raw.issues);
		expect([refined.inputHash, refined.sourceHash, refined.root]).toEqual([raw.inputHash, raw.sourceHash, raw.root]);
		expect(refined.version).toBe(SCORE_ROLES_VERSION);
		expect(SCORE_ROLES_VERSION).toBe("interlinked-source-roles-v5");
	});
	it("does not change the raw inventory", () => {
		expect(raw.files).toHaveLength(12);
		expect(raw.version).toBe("interlinked-source-roles-v4");
	});
	it("leaves an inventory with nothing to set aside equal in content", () => {
		const plain = inventory({ "src/a.ts": "export const a = 1;\n" });
		expect(refineInventory(plain)).toEqual({ ...plain, version: SCORE_ROLES_VERSION });
	});
});
