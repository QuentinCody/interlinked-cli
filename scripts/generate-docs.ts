/**
 * Family order is fixed by spec: quality → security-shape → injection →
 * cross-agent. Detectors within each family are sorted by id for stable
 * output.
 */
const SEQUENCE_FAMILY_ORDER: ReadonlyArray<SequenceDetectorFamily> = [
	"quality",
	"security-shape",
	"injection",
	"cross-agent",
];

const SEQUENCE_FAMILY_HEADERS: Record<SequenceDetectorFamily, string> = {
	quality: "Quality",
	"security-shape": "Security-Shape",
	injection: "Injection",
	"cross-agent": "Cross-Agent",
};

/**
 * One-line family description used as the header preamble in the generated
 * doc. Sourced from `src/harness/sequence-checks/types.ts` (the
 * `SequenceDetectorFamily` docstring) so the file is single-sourced.
 */
const SEQUENCE_FAMILY_BLURBS: Record<SequenceDetectorFamily, string> = {
	quality:
		"Coverage, doc drift, refactor hygiene, and plan-adherence shapes the per-file checks can't see.",
	"security-shape":
		"Supply-chain, env injection, and repetition shapes — secret-then-network, download-then-execute, repeated-without-observe.",
	injection:
		"Lethal-trifecta / prompt-injection / exfiltration shapes — defense-in-depth across private data, untrusted content, and external comms.",
	"cross-agent":
		"Multi-player staleness / coordination shapes — stale-read-then-write, subagent-divergence, overwrite-after-other-agent.",
};

function generateSequenceDetectorsDoc(): string {
	const detectors = ALL_SEQUENCE_DETECTORS;
	const lines: string[] = [
		"<!-- Auto-generated by scripts/generate-docs.ts — do not edit manually -->",
		"# Trajectory Sequence Detectors",
		"",
		`${detectors.length} sequence detectors registered.`,
		"These run against the session trajectory (a per-session in-memory record of prior tool calls)",
		"on PreToolUse and Stop events. Sibling family to per-file content checks but the contract is",
		"different — sequence detectors fire on trajectory shape, not file content.",
		"",
	];

	// Group by family
	const byFamily = new Map<SequenceDetectorFamily, SequenceDetector[]>();
	for (const fam of SEQUENCE_FAMILY_ORDER) {
		byFamily.set(fam, []);
	}
	for (const detector of detectors) {
		const bucket = byFamily.get(detector.family);
		if (bucket) bucket.push(detector);
	}

	for (const family of SEQUENCE_FAMILY_ORDER) {
		const famDetectors = byFamily.get(family) ?? [];
		if (famDetectors.length === 0) continue;

		// Stable alphabetical sort within family
		const sorted = [...famDetectors].sort((a, b) => a.id.localeCompare(b.id));

		lines.push(`## ${SEQUENCE_FAMILY_HEADERS[family]}`);
		lines.push("");
		lines.push(SEQUENCE_FAMILY_BLURBS[family]);
		lines.push("");

		for (const detector of sorted) {
			const defaultState = detector.default_enabled ? "enabled" : "disabled";
			lines.push(`### \`${detector.id}\``);
			lines.push(`- **Phase:** \`${detector.phase}\``);
			lines.push(`- **Default:** \`${defaultState}\``);
			lines.push(`- **Determinism:** \`${detector.determinism}\``);
			lines.push(`- **Description:** ${detector.description}`);
			lines.push("");
		}
	}

	return lines.join("\n");
}

