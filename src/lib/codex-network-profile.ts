import { closeSync, lstatSync, mkdirSync, openSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { networkOrigins } from "./network-access.js";

/** Separate config profile: no TOML rewriting or changes to the user's default posture. */
export function codexNetworkProfile(name: string, endpoints: string[]) {
    if (!/^[a-z][a-z0-9-]{0,62}$/.test(name)) {
        throw new Error("Profile names must start with a lowercase letter and contain only lowercase letters, digits and hyphens (maximum 63 characters).");
    }
    const hosts = [...new Set(networkOrigins(endpoints).map((origin) => new URL(origin).hostname))].sort();
    const text = [
        "# Generated by interlinked network codex-profile. Select with codex --profile " + name,
        "# Host rules cover all ports. Managed requirements still constrain this profile.",
        "# Remove conflicting legacy sandbox_mode/sandbox_workspace_write settings before use.",
        `default_permissions = "${name}"`,
        "",
        "[features]",
        "hooks = true",
        "network_proxy = true",
        "",
        `[permissions.${name}]`,
        'extends = ":workspace"',
        "",
        `[permissions.${name}.network]`,
        "enabled = true",
        "",
        `[permissions.${name}.network.domains]`,
        ...hosts.map((host) => `${JSON.stringify(host)} = "allow"`),
        "",
    ].join("\n");
    return { name, hosts, text };
}

/** Never replace a custom profile or follow a profile-file symlink. */
export function installCodexNetworkProfile(name: string, endpoints: string[], codexHome = process.env.CODEX_HOME || join(homedir(), ".codex")) {
    const profile = codexNetworkProfile(name, endpoints);
    const path = join(codexHome, `${name}.config.toml`);
    mkdirSync(codexHome, { recursive: true });
    let fd: number;
    try {
        fd = openSync(path, "wx", 0o600);
    } catch (error) {
        if (!(error instanceof Error) || !("code" in error) || error.code !== "EEXIST") throw error;
        if (lstatSync(path).isFile() && readFileSync(path, "utf8") === profile.text) {
            return { ...profile, path, changed: false };
        }
        throw new Error(`Profile already exists with different content or is not a regular file: ${path}. Choose another name or review it manually.`);
    }
    try {
        writeFileSync(fd, profile.text);
    } finally {
        closeSync(fd);
    }
    return { ...profile, path, changed: true };
}
