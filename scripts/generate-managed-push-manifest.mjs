import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import ts from "typescript";

const entries = ["scripts/git-hooks/pre-push", "scripts/run-resource-bounded.ts", "scripts/pre-push-coverage.mjs", "package.json", "package-lock.json"];
const external = new Set(["typescript"]);

function options(argv) {
    const result = { root: process.cwd(), output: null, check: false };
    for (let i = 0; i < argv.length; i++) {
        if (argv[i] === "--check") result.check = true;
        else if (argv[i] === "--root" && argv[i + 1]) result.root = resolve(argv[++i]);
        else if (argv[i] === "--output" && argv[i + 1]) result.output = resolve(argv[++i]);
        else throw new Error("Usage: generate-managed-push-manifest.mjs [--check] [--root path] [--output path]");
    }
    result.output ??= resolve(result.root, "src/harness/managed-push-manifest.ts");
    return result;
}

function dependencies(path, source) {
    const found = [];
    const ast = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);
    function visit(node) {
        if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier) {
            if (!ts.isStringLiteral(node.moduleSpecifier)) throw new Error("Computed runtime dependency: " + path);
            found.push(node.moduleSpecifier.text);
        }
        if (ts.isCallExpression(node) && (node.expression.kind === ts.SyntaxKind.ImportKeyword || (ts.isIdentifier(node.expression) && node.expression.text === "require"))) {
            if (!node.arguments[0] || !ts.isStringLiteral(node.arguments[0])) throw new Error("Computed runtime dependency: " + path);
            found.push(node.arguments[0].text);
        }
        ts.forEachChild(node, visit);
    }
    visit(ast);
    return found;
}

function collect(root) {
    const files = new Map();
    function walk(path) {
        if (files.has(path)) return;
        if (path.startsWith("../") || path.startsWith("/") || files.size >= 128) throw new Error("Unbounded runtime dependency closure");
        const bytes = readFileSync(resolve(root, path));
        files.set(path, createHash("sha256").update(bytes).digest("hex"));
        if (!/\.(?:ts|mjs|js)$/.test(path)) return;
        for (const spec of dependencies(path, bytes.toString("utf8"))) {
            if (spec.startsWith("node:") || external.has(spec)) continue;
            if (!spec.startsWith(".")) throw new Error("Unrecognized runtime package: " + spec);
            let target = resolve(root, dirname(path), spec);
            if (!existsSync(target)) target = target.replace(/\.js$/, ".ts");
            walk(relative(root, target).replaceAll("\\", "/"));
        }
    }
    for (const entry of entries) walk(entry);
    return Object.fromEntries([...files].sort(([left], [right]) => left.localeCompare(right)));
}

const config = options(process.argv.slice(2));
const files = collect(config.root);
const output = 'import type { ManagedPushTrust } from "./managed-push-snapshot.js";\n\n' +
    '// Generated by scripts/generate-managed-push-manifest.mjs; regenerate after gate runtime changes.\n' +
    'export const MANAGED_PUSH_TRUST: ManagedPushTrust = {\n    files: ' + JSON.stringify(files, null, 4).replaceAll("\n", "\n    ") + ',\n    packages: ["tsx", "typescript"],\n};\n';
if (config.check) {
    if (readFileSync(config.output, "utf8") !== output) throw new Error("Managed push trust manifest is stale; regenerate it after reviewing runtime changes");
} else writeFileSync(config.output, output);
console.log(`Managed push trust: ${Object.keys(files).length} source files${config.check ? " verified" : " generated"}.`);
