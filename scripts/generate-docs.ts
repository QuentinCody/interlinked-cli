import { execFileSync } from "node:child_process";

function getHelpOutput(args: string[]): string {
	let raw: string;
	try {
		raw = execFileSync(
			process.execPath,
			["--import", "tsx", join(import.meta.dirname, "..", "src", "index.ts"), ...args, "--help"],
			{
				encoding: "utf-8",
				timeout: 10_000,
				env: { ...process.env, INTERLINKED_SKIP_IMPLICIT_ENTRY: "1" },
			},
		).trim();
	} catch (err) {
		// Commander writes help to stdout and exits with code 0, but execFileSync
		// may throw if the process exits before consuming all stdin. Try stderr fallback.
		const e = err as { stdout?: string; stderr?: string };
		raw = (e.stdout || e.stderr || "").trim();
	}
	// Strip the repeated "Interface boundaries" / "Quick start" footer that commander appends
	const footerIdx = raw.indexOf("\nInterface boundaries:");
	const withoutFooter = footerIdx >= 0 ? raw.slice(0, footerIdx).trimEnd() : raw;
	return sanitizeHelpOutput(withoutFooter);
}

function sanitizeHelpOutput(output: string): string {
	return output.split(process.cwd()).join("<cwd>");
}

function generateCliReference(): string {
	const lines: string[] = [
		"<!-- Auto-generated by scripts/generate-docs.ts — do not edit manually -->",
		"# Interlinked CLI Command Reference",
		"",
	];

	// Top-level help
	const topHelp = getHelpOutput([]);
	lines.push("## Overview", "", "```", topHelp, "```", "");

	// Extract top-level command names from help output
	const commandNames = [
		"structure",
		"verify",
		"metrics",
		"harness",
		"checkpoint",
		"tasks",
		"workspace",
		"index",
		"trace",
		"guard",
		"git",
	];

	// Commands with subcommands — mirror the groups registered in src/index.ts.
	const commandsWithSubs: Record<string, string[]> = {
		structure: ["init", "scan", "status", "accept", "doctor", "baseline"],
		metrics: ["coupling", "arch", "rework"],
		checkpoint: ["list", "show", "compare", "prune", "archive"],
		tasks: ["list", "create", "show", "claim", "complete"],
		workspace: ["list", "switch"],
		index: ["build", "update", "status", "query"],
		trace: ["export", "import"],
		harness: ["start", "stop", "restart", "status", "test"],
		guard: ["install", "check", "status", "uninstall"],
		git: ["context", "link-checkpoint"],
		reminder: ["add", "list", "remove"],
		coverage: ["check", "baseline"],
		mutation: ["check", "baseline"],
		completions: ["bash", "zsh", "fish"],
	};

	for (const cmd of commandNames) {
		const cmdHelp = getHelpOutput([cmd]);
		if (!cmdHelp) continue;

		const title = cmd.charAt(0).toUpperCase() + cmd.slice(1);
		lines.push(`## ${title}`, "", "```", cmdHelp, "```", "");

		const subs = commandsWithSubs[cmd];
		if (subs) {
			for (const sub of subs) {
				const subHelp = getHelpOutput([cmd, sub]);
				if (!subHelp) continue;
				lines.push(`### ${cmd} ${sub}`, "", "```", subHelp, "```", "");
			}
		}
	}

	// Also document standalone commands with notable options
	const standaloneCommands = [
		"enable", "disable", "status", "activity", "doctor", "clean",
		"login", "sync", "send", "inbox", "watch",
	];
	lines.push("## Other Commands", "");
	for (const cmd of standaloneCommands) {
		const cmdHelp = getHelpOutput([cmd]);
		if (!cmdHelp) continue;
		lines.push(`### ${cmd}`, "", "```", cmdHelp, "```", "");
	}

	return lines.join("\n");
}

