import { describe, expect, it } from "vitest";
import { isGeneratedFile } from "../../harness/checks/shared.js";
import { classifyByPath, refineByContent } from "./role-evidence.js";
import { classifyByContent, headerBannerEvidence, markerEvidence } from "./role-evidence-content.js";

describe("headerBannerEvidence: a strict generator banner in the LEADING comment block", () => {
	// MUST-FIRE
	it.each([
		["Go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: a.proto\n\npackage a\n"],
		["Fern TypeScript", "// This file was auto-generated by Fern from our API Definition.\n\nexport type A = string;\n"],
		["after a shebang, an encoding line and a license block", "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n# Copyright 2026 Someone\n# Licensed under the Apache License\n\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\nimport sys\n"],
		["OpenAPI Generator Python docstring", `${"# license line\n".repeat(9)}\n"""\nAdmin API\n\nGenerated by OpenAPI Generator (https://openapi-generator.tech)\n\nDo not edit the class manually.\n"""\nimport os\n`],
		["OpenAPI Generator TypeScript block comment", "/* tslint:disable */\n/**\n * API\n * NOTE: This class is auto generated by OpenAPI Generator (https://openapi-generator.tech).\n * Do not edit the class manually.\n */\nexport const a = 1;\n"],
		["@generated tag", "/* @generated */\nexport const a = 1;\n"],
		["orval", "/**\n * Generated by orval v7\n * Do not edit manually.\n */\nexport type A = string;\n"],
		["C# auto-generated block", "//------------------------------------------------------------------------------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n//------------------------------------------------------------------------------\nnamespace A {}\n"],
	])("%s", (_name, content) => {
		const found = headerBannerEvidence(content);
		expect(found).toMatchObject({ kind: "marker" });
		expect(found?.detail).toMatch(/^line \d+: /);
	});

	it("reports the line of the banner", () => {
		expect(headerBannerEvidence("// header\n\n// @generated\nexport const a = 1;\n")?.detail).toMatch(/^line 3: /);
	});

	// MUST-NOT-FIRE (the trap rows of the independent census)
	it.each([
		["a comment above one import in hand-written code", "import asyncio\n\nfrom grpclib.client import Channel\n\n# generated by protoc\nfrom .primes_pb2 import Request\n"],
		["a banner after the first code statement, even inside ten lines", "import os\n# DO NOT EDIT\nX = 1\n"],
		["a vendored C header that mentions auto-generated vmlinux.h after code", "/* SPDX-License-Identifier: GPL */\n#ifndef __X__\n#define __X__\n\n/*\n * vmlinux.h (auto-generated from BTF) or linux/types.h\n */\n#include \"y.h\"\n"],
		["prose in the leading doc comment that says generated code", "/**\n * A line-oriented diff.\n * The inputs are a few dozen lines of\n * generated code, and a diff library would be a new dependency.\n */\nconst A = 3\n"],
		["the banner text inside a string literal", "export const note = \"DO NOT EDIT\";\n"],
		["a hand-written generator script that only mentions generation", "// Generates the registry files from the schema.\nexport function generate() {}\n"],
		["a python docstring that opens after code", "import os\nX = \"\"\"\nGenerated by OpenAPI Generator\n\"\"\"\n"],
		["a hand-written module docstring about generation", "\"\"\"Helpers that generate ids.\n\nThe generator is hand written.\n\"\"\"\nimport os\n"],
		["an empty file", ""],
	])("%s", (_name, content) => {
		expect(headerBannerEvidence(content)).toBeNull();
	});
});

describe("the measurement population uses the header rule; the gates keep their own function", () => {
	it("refineByContent moves a product file with a header banner to generated with kind marker", () => {
		const decision = refineByContent(classifyByPath("src/a.ts"), "// Code generated by x. DO NOT EDIT.\nexport const a = 1;\n");
		expect(decision).toMatchObject({ role: "generated", evidence: { kind: "marker" }, from: "product" });
		expect(classifyByContent("// @generated\nexport const a = 1;\n")).toMatchObject({ role: "generated", evidence: { kind: "marker" } });
	});

	it("refineByContent leaves a banner outside the header position as product (it stays only a label)", () => {
		const content = "import os\n# DO NOT EDIT\nX = 1\n";
		expect(refineByContent(classifyByPath("src/a.py"), content).role).toBe("product");
		expect(markerEvidence(content)).not.toBeNull();
	});

	it("PIN: the per-edit gate exemption `isGeneratedFile` is unchanged: any marker in the first 20 lines, header position or not", () => {
		expect(isGeneratedFile("import os\n# DO NOT EDIT\nX = 1\n")).toBe(true);
		expect(isGeneratedFile("import asyncio\n\n# generated by protoc\nfrom .a_pb2 import R\n")).toBe(false);
		expect(isGeneratedFile("/**\n * generated code, and a diff library\n */\nconst A = 3\n")).toBe(false);
		expect(isGeneratedFile(`${"x = 1\n".repeat(25)}# DO NOT EDIT\n`)).toBe(false);
		expect(isGeneratedFile("// auto generated by a tool\nexport const a = 1;\n")).toBe(true);
	});
});
