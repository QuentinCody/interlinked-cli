import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { afterEach, beforeEach, expect, it } from "vitest";
import { collectScoringSources } from "./source-census.js";

let root: string;
beforeEach(() => { root = mkdtempSync(join(process.cwd(), "scratch/scoring-census-")); execFileSync("git", ["init", "--quiet", root]); });
afterEach(() => rmSync(root, { recursive: true, force: true }));

it("preserves the legacy runtime size bound and admits the same full source for a foreground survey", () => {
	const content = "// ordinary source comment\n".repeat(90_000) + "export function value() { return 1; }\n";
	writeFileSync(join(root, "source.ts"), content);
	const runtime = collectScoringSources(root);
	expect(runtime.sources).toEqual([]); expect(runtime.notMeasured).toEqual([{ file: "source.ts", reason: expect.stringContaining("2 MiB") }]);
	const foreground = collectScoringSources(root, { resourcePolicy: "foreground-survey" });
	expect(foreground.sources).toMatchObject([{ file: "source.ts", content }]); expect(foreground.notMeasured).toEqual([]);
});

it("keeps Git-visible scope and reports failed Git discovery instead of scanning ignored fallback content", () => {
	writeFileSync(join(root, ".gitignore"), "ignored.ts\n"); writeFileSync(join(root, "source.ts"), "export {};\n"); writeFileSync(join(root, "ignored.ts"), "export {};\n");
	expect(collectScoringSources(root, { resourcePolicy: "foreground-survey" }).sources.map(file => file.file)).toEqual(["source.ts"]);
	rmSync(join(root, ".git"), { recursive: true }); writeFileSync(join(root, ".git"), "gitdir: missing\n");
	const failed = collectScoringSources(root, { resourcePolicy: "foreground-survey" });
	expect(failed.sources).toEqual([]); expect(failed.discoveryIssues.length).toBeGreaterThan(0);
});

it("sets aside vendored and self-declared generated source with its evidence, and keeps hand-written source", () => {
	mkdirSync(join(root, ".yarn/releases"), { recursive: true });
	writeFileSync(join(root, ".yarn/releases/yarn.cjs"), "function a(x) { return x; }\n");
	writeFileSync(join(root, "user.pb.ts"), "export const made = 1;\n");
	writeFileSync(join(root, "declared.ts"), "// Autogenerated file\nexport const declared = 1;\n");
	writeFileSync(join(root, "hand.ts"), "// Generated IDs are stable.\nexport const hand = 1;\n");
	const census = collectScoringSources(root, { resourcePolicy: "foreground-survey" });
	// A header alone ("Autogenerated file") does not set declared.ts aside: it stays measured.
	expect(census.sources.map(source => source.file)).toEqual(["declared.ts", "hand.ts"]);
	expect(census.setAside).toEqual([
		{ file: ".yarn/releases/yarn.cjs", role: "vendor", evidence: { kind: "tool-path", detail: ".yarn/releases/" } },
		{ file: "user.pb.ts", role: "generated", evidence: { kind: "path", detail: ".pb.ts" } }]);
});

it("cancels foreground discovery without converting cancellation to a source gap", () => {
	const controller = new AbortController(); controller.abort(new Error("operator cancelled survey"));
	expect(() => collectScoringSources(root, { resourcePolicy: "foreground-survey", signal: controller.signal })).toThrow("operator cancelled survey");
});
