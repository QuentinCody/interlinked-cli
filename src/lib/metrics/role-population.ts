import { lstatSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { SCORE_ROLES_VERSION } from "./inventory-refine.js";
import { emptyEvidenceCounts, type RepositoryInventory, type RoleEvidenceKind, type SourceRole } from "./measurement-types.js";
import { classifyByPath, refineByContent, type RoleDecision } from "./role-evidence.js";
import { applyRepoEvidence, loadRepoEvidence } from "./role-repo-evidence.js";

/**
 * One file population for every analysis command. The score report applies source roles v5 (path evidence plus content shape);
 * the other commands used to apply the path-only gate population, so they disagreed about which files are "the code".
 * This module is the single place that decides, from the v5 role, whether a file is measured or set aside, and it counts both.
 */
export const POPULATION_LISTED_CAP = 50;
const MAX_READ_BYTES = 16 * 1024 * 1024;

export interface SetAsideFile { file: string; role: SourceRole; evidence: RoleEvidenceKind; detail: string; bytes: number | null; }
export interface PopulationSummary {
	rolesVersion: string;
	/** Every file the command looked at. */
	files: number;
	/** Files that stay in the population after set-aside (product and test). A command may still skip some for its own reason. */
	measured: number;
	/** Files seen, by v5 role. */
	roles: Record<string, number>;
	setAside: {
		files: number;
		/** Set-aside files by role: generated, vendor, asset, documentation, configuration, fixture. */
		byRole: Record<string, number>;
		/** Generated and vendor files by the kind of evidence that set them aside. */
		byEvidence: Record<RoleEvidenceKind, number>;
		/** Generated and vendor files, largest first, capped; the other roles are counted only. */
		listed: SetAsideFile[];
		omitted: number;
		/** Files in the separate bucket `unlinted` (the repository's own linter does not lint them), per rule (`tool key pattern (file:line)`), largest first. */
		toolConfig: Array<{ rule: string; files: number }>;
	};
	/** Directories whose files look generated by structure alone. Their files stay measured; this list is for the owner. */
	candidates: Array<{ dir: string; files: number; detail: string }>;
}

export interface Population {
	/** Returns true when the file stays in the measured population. */
	add(file: string, decision: RoleDecision, bytes: number | null): boolean;
	summary(): PopulationSummary;
}

/** Product and test files are measured; every other role is set aside. How a command treats tests stays that command's own rule. */
function isMeasuredRole(role: SourceRole): boolean {
	return role === "product" || role === "test";
}

/** The path role of a file plus the repository's own evidence (generator config and commands, `.gitattributes`, linter excludes), read from the files under `root`. */
export function classifyByPathAt(root: string, file: string): RoleDecision {
	return applyRepoEvidence(loadRepoEvidence(root), file, classifyByPath(file));
}

/** The v5 role of a file whose content is in hand; `root`, when given, adds the repository's linter excludes. */
export function decideRole(file: string, content: string, root?: string): RoleDecision {
	return refineByContent(root === undefined ? classifyByPath(file) : classifyByPathAt(root, file), content);
}

/**
 * The v5 role of a file on disk, with its size. Content is read for every product file within the size bound (a strict banner in the header, or a minified shape,
 * sets it aside); a missing file, a link or an unreadable file keeps its path-only role so that the caller reports it instead of hiding it.
 */
export function classifyFileAt(root: string, file: string): { decision: RoleDecision; bytes: number | null } {
	const byPath = classifyByPathAt(root, file);
	try {
		const absolute = join(root, file), stat = lstatSync(absolute);
		if (!stat.isFile()) return { decision: byPath, bytes: null };
		const readable = byPath.role === "product" && stat.size <= MAX_READ_BYTES;
		return { decision: readable ? refineByContent(byPath, readFileSync(absolute, "utf8")) : byPath, bytes: stat.size };
	} catch { return { decision: byPath, bytes: null }; }
}

/** Classify a file on disk and count it. */
export function addFileAt(population: Population, root: string, file: string): { kept: boolean; decision: RoleDecision } {
	const { decision, bytes } = classifyFileAt(root, file);
	return { kept: population.add(file, decision, bytes), decision };
}

const emptyEvidence = emptyEvidenceCounts;
const bump = (counts: Record<string, number>, key: string): void => { counts[key] = (counts[key] ?? 0) + 1; };

function sortedCounts(counts: Record<string, number>): Record<string, number> {
	return Object.fromEntries(Object.entries(counts).sort(([a], [b]) => a.localeCompare(b)));
}

function bySize(a: SetAsideFile, b: SetAsideFile): number {
	return (b.bytes ?? -1) - (a.bytes ?? -1) || a.file.localeCompare(b.file);
}

interface Tally {
	byRole: Record<string, number>; byEvidence: Record<RoleEvidenceKind, number>; byRule: Record<string, number>;
	generatedOrVendor: SetAsideFile[]; candidates: Map<string, { files: number; detail: string }>;
}

function countCandidate(tally: Tally, candidate: { dir: string; detail: string }): void {
	tally.candidates.set(candidate.dir, { files: (tally.candidates.get(candidate.dir)?.files ?? 0) + 1, detail: candidate.detail });
}

/** Count one set-aside file: its role, and, when it has evidence, the evidence kind and the bucket (`unlinted` rule, or the listed generated/vendor file). */
function countSetAside(tally: Tally, file: string, decision: RoleDecision & { evidence: NonNullable<RoleDecision["evidence"]> }, bytes: number | null): void {
	const { role, evidence } = decision;
	if (role === "unlinted") bump(tally.byRule, evidence.detail);
	else if (role === "generated" || role === "vendor") tally.generatedOrVendor.push({ file, role, evidence: evidence.kind, detail: evidence.detail, bytes });
	else return;
	tally.byEvidence[evidence.kind]++;
}

const byRuleRows = (byRule: Record<string, number>): Array<{ rule: string; files: number }> =>
	Object.entries(byRule).map(([rule, count]) => ({ rule, files: count })).sort((a, b) => b.files - a.files || a.rule.localeCompare(b.rule));

export function createPopulation(rolesVersion: string = SCORE_ROLES_VERSION): Population {
	const roles: Record<string, number> = {};
	const tally: Tally = { byRole: {}, byEvidence: emptyEvidence(), byRule: {}, generatedOrVendor: [], candidates: new Map() };
	let files = 0, measured = 0, setAside = 0;
	return {
		add(file, decision, bytes) {
			files++;
			bump(roles, decision.role);
			if (isMeasuredRole(decision.role)) {
				measured++;
				if (decision.candidate !== undefined) countCandidate(tally, decision.candidate);
				return true;
			}
			setAside++;
			bump(tally.byRole, decision.role);
			if (decision.evidence !== null) countSetAside(tally, file, { ...decision, evidence: decision.evidence }, bytes);
			return false;
		},
		summary() {
			const listed = [...tally.generatedOrVendor].sort(bySize);
			return { rolesVersion, files, measured, roles: sortedCounts(roles),
				setAside: { files: setAside, byRole: sortedCounts(tally.byRole), byEvidence: tally.byEvidence, listed: listed.slice(0, POPULATION_LISTED_CAP), omitted: Math.max(0, listed.length - POPULATION_LISTED_CAP),
						toolConfig: byRuleRows(tally.byRule) },
				candidates: [...tally.candidates].map(([dir, value]) => ({ dir, ...value })).sort((a, b) => b.files - a.files || a.dir.localeCompare(b.dir)).slice(0, POPULATION_LISTED_CAP) };
		},
	};
}

/** Split sources whose content is in hand into the measured ones (order kept) and the census of all of them. */
export function partitionSources<T extends { file: string; content: string }>(sources: readonly T[], root?: string): { kept: T[]; population: PopulationSummary } {
	const population = createPopulation(), kept: T[] = [];
	for (const source of sources) if (population.add(source.file, decideRole(source.file, source.content, root), source.content.length)) kept.push(source);
	return { kept, population: population.summary() };
}

/** The same summary for a refined inventory (`refineInventory`), as diagnostics and the score report hold it. */
export function summarizeInventoryPopulation(inventory: RepositoryInventory): PopulationSummary {
	const population = createPopulation(inventory.version);
	for (const file of inventory.files) {
		const decision: RoleDecision = { role: file.role, evidence: file.moved?.evidence ?? null, from: file.moved?.from ?? null };
		if (file.candidateGenerated !== undefined) decision.candidate = file.candidateGenerated;
		population.add(file.path, decision, file.content.length);
	}
	for (const entry of inventory.excluded) population.add(entry.path, { role: entry.role, evidence: entry.evidence ?? null, from: entry.from ?? null }, entry.lines ?? null);
	return population.summary();
}
