import { describe, expect, it } from "vitest";
import { classifyByPath, countLines, excludedEntry, refineByContent } from "./role-evidence.js";

describe("content refinement moves only authored product code, and records where it came from", () => {
	it("keeps a product file with a banner outside the header position a product: it is only labelled", () => {
		const path = classifyByPath("lib/csc/framework-mappings.ts");
		expect(refineByContent(path, "export default {};\n// AUTO-GENERATED by scripts/gen.py\n")).toEqual({ role: "product", evidence: null, from: null });
	});
	it("sets aside a product file whose leading comment block holds a strict banner, with the line", () => {
		const path = classifyByPath("lib/csc/framework-mappings.ts");
		expect(refineByContent(path, "// AUTO-GENERATED by scripts/gen.py\nexport default {};\n")).toMatchObject({ role: "generated", evidence: { kind: "marker" }, from: "product" });
	});
	it("moves a minified product file and keeps the structural evidence", () => {
		const refined = refineByContent(classifyByPath("web/bundle.js"), `${"var f=function(a,b){return a+b},x=f(1,2),y=f(x,3);".repeat(600)}\n`);
		expect(refined).toMatchObject({ role: "generated", evidence: { kind: "shape" }, from: "product" });
	});
	it("leaves a hand-written product file, a test file and an already-excluded file alone", () => {
		const text = "// @generated\nexport const a = 1;\n";
		expect(refineByContent(classifyByPath("src/a.ts"), "export const a = 1;\n").role).toBe("product");
		expect(refineByContent(classifyByPath("src/a.test.ts"), text).role).toBe("test");
		expect(refineByContent(classifyByPath("node_modules/a/index.js"), text)).toMatchObject({ role: "vendor", evidence: { kind: "path" } });
	});
	it("keeps the earlier path evidence when content adds none", () => {
		expect(refineByContent(classifyByPath("packages/ui/mocks/a.ts"), "export const a = 1;\n")).toMatchObject({ role: "test", evidence: { kind: "path" }, from: "product" });
	});
});

describe("excluded entries and line counts", () => {
	it("records evidence, the earlier role and the line count", () => {
		const decision = classifyByPath(".yarn/releases/yarn.cjs");
		expect(excludedEntry(".yarn/releases/yarn.cjs", decision, 874)).toEqual({ path: ".yarn/releases/yarn.cjs", role: "vendor", reason: "Excluded by source-role policy",
			evidence: { kind: "tool-path", detail: ".yarn/releases/" }, from: "product", lines: 874 });
	});
	it("omits optional fields for a role with no evidence", () => {
		expect(excludedEntry("public/logo.png", classifyByPath("public/logo.png"))).toEqual({ path: "public/logo.png", role: "asset", reason: "Excluded by source-role policy" });
	});
	it("counts physical lines with and without a trailing newline", () => {
		expect([countLines(""), countLines("a"), countLines("a\n"), countLines("a\nb"), countLines("a\nb\n")]).toEqual([0, 1, 1, 2, 2]);
	});
});

describe("path evidence keeps the existing path-only roles and names the matching rule", () => {
	it("reports the matched directory or name for vendor and generated roles", () => {
		expect(classifyByPath("node_modules/left-pad/index.js")).toMatchObject({ role: "vendor", evidence: { kind: "path", detail: "node_modules/" } });
		expect(classifyByPath("apps/web/src/routeTree.gen.ts")).toMatchObject({ role: "generated", evidence: { kind: "path", detail: ".gen." } });
		expect(classifyByPath("types/index.d.ts")).toMatchObject({ role: "generated", evidence: { kind: "path" } });
	});
	it("gives authored files no evidence", () => {
		expect(classifyByPath("src/main.ts")).toEqual({ role: "product", evidence: null, from: null });
		expect(classifyByPath("src/main.test.ts")).toEqual({ role: "test", evidence: null, from: null });
	});
});

describe("tool-path evidence: committed package-manager and tool drops are vendored", () => {
	// MUST-CLASSIFY
	it.each([
		[".yarn/releases/yarn-berry.cjs", ".yarn/releases/"],
		["app/.yarn/plugins/@yarnpkg/plugin-workspace-tools.cjs", ".yarn/plugins/"],
		[".yarn/sdks/typescript/lib/tsc.js", ".yarn/sdks/"],
		[".pnp.cjs", ".pnp.cjs"],
		[".pnp.loader.mjs", ".pnp.loader.mjs"],
		["third_party/lib/util.ts", "third_party/"],
		["pkg/third-party/lib/util.js", "third-party/"],
		["web/vendored/zlib.js", "vendored/"],
		["web/bower_components/jquery/src/core.js", "bower_components/"],
		["public/js/app.min.js", ".min.js"],
		["static/theme.min.mjs", ".min.mjs"],
	])("moves %s to vendor", (path, detail) => {
		expect(classifyByPath(path)).toEqual({ role: "vendor", evidence: { kind: "tool-path", detail }, from: "product" });
	});
	// MUST-NOT-CLASSIFY
	it.each([
		"src/yarn/releases.ts", "src/third_party_notes.ts", "src/vendored-check.ts", "src/pnp.ts",
		"src/minimal.ts", "src/admin.js", "src/min.js",
	])("keeps the look-alike %s authored", path => {
		expect(classifyByPath(path).role).toBe("product");
		expect(classifyByPath(path).evidence).toBeNull();
	});
});

describe("generator name shapes: only names that a generator produces and a person does not", () => {
	// MUST-CLASSIFY
	it.each([
		["api/user.pb.go", ".pb.go"], ["src/proto/user.pb.ts", ".pb.ts"], ["web/user_pb.js", "_pb.js"],
		["py/user_pb2.py", "_pb2.py"], ["py/user_pb2_grpc.py", "_pb2_grpc.py"],
		["pkg/zz_generated.deepcopy.go", "zz_generated."], ["src/schema_generated.ts", "_generated.ts"],
	])("moves %s to generated by name", (path, detail) => {
		expect(classifyByPath(path)).toEqual({ role: "generated", evidence: { kind: "path", detail }, from: "product" });
	});
	// MUST-NOT-CLASSIFY: `_gen` names are often hand-written
	it.each([
		"rust/crates/core/src/input_gen.rs", "src/key_gen.rs", "src/id_gen.py", "src/generator.ts",
		"src/generated-ids.ts", "src/pb.ts", "src/graphql.ts", "src/user.graphql.ts", "src/dart_g.ts",
	])("keeps %s authored", path => {
		expect(classifyByPath(path).role).toBe("product");
		expect(classifyByPath(path).evidence).toBeNull();
	});
});

describe("mocks directories are test support", () => {
	it("moves a data mock directory out of the product role", () => {
		expect(classifyByPath("packages/ui/mocks/resources/orders/full.ts")).toEqual({ role: "test", evidence: { kind: "path", detail: "mocks/" }, from: "product" });
	});
	it("keeps singular mock directories, which can hold shipped mock servers", () => {
		expect(classifyByPath("lib/fleet/mock/handler.ts").role).toBe("product");
	});
});

describe("path evidence applies only to files that were authored candidates", () => {
	it("leaves documentation, configuration and assets alone", () => {
		expect(classifyByPath("third_party/README.md").role).toBe("documentation");
		expect(classifyByPath(".yarn/releases/notes.json").role).toBe("configuration");
		expect(classifyByPath("public/logo.png").role).toBe("asset");
	});
	it("normalises backslashes", () => {
		expect(classifyByPath(".yarn\\releases\\yarn.cjs").role).toBe("vendor");
	});
});
