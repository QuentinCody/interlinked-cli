import { describe, expect, it } from "vitest";
import { isDocName, readDocStatements } from "./role-generator-docs.js";

const tracked = ["src/api/a.py", "src/api/b.py", "scripts/gen.sh", "docs/guide.md", "README.md"];
const found = (file: string, text: string): string[] => readDocStatements(file, text, tracked).map((c) => `${c.tool} ${c.target}@${c.line}`);

describe("readDocStatements", () => {
	it("MUST-FIRE: a line that names a generator and an existing directory", () => {
		expect(found("openapi/SOURCE.md", "# Source\n\nThe client in `src/api` is generated by openapi-python-client==0.29.1.\n")).toEqual(["openapi-python-client src/api@3"]);
	});

	it("MUST-FIRE: a bare path token, and a path relative to the document", () => {
		expect(found("README.md", "Run sqlc generate to rewrite src/api/a.py.\n")).toEqual(["sqlc src/api/a.py@1"]);
		expect(found("src/README.md", "orval generates ./api here.\n")).toEqual(["orval src/api@1"]);
	});

	it("MUST-NOT-FIRE: a generator named with no path (the README trap)", () => {
		expect(found("README.md", "This project uses openapi-python-client to generate its SDK.\n")).toEqual([]);
	});

	it("MUST-NOT-FIRE: a path with no generator, and a line that says nothing of generation", () => {
		expect(found("README.md", "The code lives in `src/api`.\nWe like orval and `src/api`.\n")).toEqual([]);
	});

	it("MUST-NOT-FIRE: a path that names nothing tracked, and a URL", () => {
		expect(found("README.md", "orval generated `src/missing/` from https://example.com/src/api\n")).toEqual([]);
	});
});

describe("isDocName", () => {
	it("reads prose files and not a changelog", () => {
		expect(isDocName("docs/a.md")).toBe(true);
		expect(isDocName("CHANGELOG.md")).toBe(false);
		expect(isDocName("src/a.ts")).toBe(false);
	});
});
